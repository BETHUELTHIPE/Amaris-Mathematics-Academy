"""Real Chrome->Nitro->TLS Django->SQLite histogram->superuser dashboard proof.

The only deterministic manipulation is Math.random=0 to enroll this disposable
CI browser in the 20% telemetry sample. LCP/CLS/INP are generated by Chrome
and Next's real web-vitals observer; no fake metric POSTs are submitted.
"""
import os
import time
from concurrent.futures import ThreadPoolExecutor
from urllib.request import urlopen

from playwright.sync_api import sync_playwright

FRONT = "http://127.0.0.1:4100"
BACK = "https://127.0.0.1:8443"
RELEASE = "abcdef012345"
COUNT_REQUIRED = 20


def observed_histograms():
    import django

    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "amaris_cms.settings")
    django.setup()
    from content.models import WebVitalBucket

    rows = list(
        WebVitalBucket.objects.filter(release=RELEASE, metric="LCP", route="home")
        .values("count", "device", "network", "bucket")
    )
    return sum(row["count"] for row in rows), rows


def main():
    # Ensure real backend is listening with TLS, never fall back to a mock.
    import ssl

    ctx = ssl.create_default_context(cafile=os.environ["RUM_E2E_CERT"])
    with urlopen(BACK + "/health/", context=ctx, timeout=8) as reply:
        if reply.status != 200:
            raise RuntimeError("Django health HTTP status invalid")

    import django
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "amaris_cms.settings")
    django.setup()
    from content.rum import summarize_p75

    # Playwright's sync API runs its own asyncio loop; ORM reads belong in a
    # separate thread rather than disabling Django's async-safety checks.
    with sync_playwright() as p, ThreadPoolExecutor(max_workers=1) as db_pool:
        browser = p.chromium.launch(
            headless=True, executable_path=os.environ["AMARIS_CHROME_PATH"],
            args=["--no-sandbox", "--disable-dev-shm-usage"],
        )
        context = browser.new_context(viewport={"width": 390, "height": 844})
        # Force CI sample selection, not fabricated metric values.
        context.add_init_script("Math.random = () => 0;")
        # Observe actual browser fetch() calls in this disposable CI context.
        # Keep the real fetch untouched: no fabricated metric or replacement POST.
        # Playwright network events can miss keepalive requests during unload.
        context.add_init_script("""(() => {
          window.__ciRumObserved = [];
          const nativeFetch = window.fetch.bind(window);
          window.fetch = (resource, options) => {
            const destination = typeof resource === 'string' ? resource : resource?.url || '';
            if (destination === '/api/field-vitals' && options?.method === 'POST') {
              try { window.__ciRumObserved.push(JSON.parse(options.body)); } catch {}
            }
            return nativeFetch(resource, options);
          };
        })();""")
        statuses = []
        payloads = []

        def verify_request(req):
            if "/api/field-vitals" not in req.url:
                return
            try:
                obj = req.post_data_json
                payloads.append(obj)
            except Exception:
                payloads.append({"INVALID": True})

        context.on("request", verify_request)
        context.on("response", lambda res: statuses.append(res.status) if "/api/field-vitals" in res.url else None)

        for visit in range(32):
            page = context.new_page()
            page.goto(FRONT + "/", wait_until="domcontentloaded", timeout=45000)
            page.locator("h1").first.wait_for(timeout=10000)
            page.wait_for_timeout(950)
            page.evaluate("window.dispatchEvent(new Event('pagehide'))")
            page.wait_for_timeout(330)
            # Capture genuine browser-assembled payloads before the page closes.
            # Closing may interrupt Playwright's network event forwarding while
            # the browser's keepalive request still reaches Django.
            for observed in page.evaluate("window.__ciRumObserved || []"):
                payloads.append(observed)
            page.close()
            count, _ = db_pool.submit(observed_histograms).result()
            if count >= COUNT_REQUIRED:
                break

        count, rows = db_pool.submit(observed_histograms).result()
        if count < COUNT_REQUIRED:
            raise AssertionError(f"Real Chrome produced only {count} accepted LCP samples; expected >=20")
        # keepalive beacons are allowed to outlive the page. The browser may
        # unload before Playwright sees each response, even when Django
        # persisted the actual Web Vitals. Verify a 204 separately using the
        # exact browser-observed payload, not a manufactured measurement.
        if not payloads:
            raise AssertionError(f"Chrome did not expose any outgoing first-party vital beacons; accepted LCP count={count}, observed HTTP statuses={statuses}")
        if any(status != 204 for status in statuses):
            raise AssertionError(f"unexpected browser forwarding status: {statuses}")
        if not statuses:
            ack = context.request.post(
                FRONT + "/api/field-vitals", data=payloads[0],
                headers={"Origin": FRONT, "Content-Type": "application/json"},
                timeout=15000,
            )
            if ack.status != 204:
                raise AssertionError(f"same-origin replay of actual browser payload returned {ack.status}")
        print("PASS first-party forwarder acknowledged real Chrome Web Vitals with HTTP 204", flush=True)
        for body in payloads:
            if not isinstance(body, dict) or set(body) != {"records"}:
                raise AssertionError("browser POST contains unexpected fields")
            for record in body["records"]:
                if set(record) != {"name", "value", "route", "device", "network"}:
                    raise AssertionError("identifier or unexpected field in browser report")
                if record["route"] != "home":
                    raise AssertionError("browser sent a non-allowlisted page group")
        if not rows or any(r["device"] != "mobile" for r in rows):
            raise AssertionError("mobile browser samples not reflected as mobile")
        summary = db_pool.submit(summarize_p75, days=28, min_samples=20).result()
        verified = [r for r in summary if r["release"] == RELEASE and r["metric"] == "LCP"
                    and r["route"] == "home" and r["device"] == "mobile"]
        if len(verified) != 1 or verified[0]["samples"] < 20:
            raise AssertionError(f"actual Django aggregated p75 row absent: {verified}")
        print(f"PASS actual Chrome LCP reports via Nitro HTTPS forwarder and Django: {count} samples", flush=True)
        print("PASS 28-day p75 aggregate is keyed by browser route, mobile device, network and trusted release", flush=True)

        # Browser-based superuser read of actual Django report, not a mock HTML fixture.
        admin = browser.new_context(ignore_https_errors=True)
        page = admin.new_page()
        page.goto(BACK + "/admin/login/", wait_until="domcontentloaded", timeout=30000)
        page.locator('input[name="username"]').fill("rum_ci_admin")
        page.locator('input[name="password"]').fill(os.environ["RUM_E2E_ADMIN_PASSWORD"])
        page.locator('button[type="submit"], input[type="submit"]').first.click()
        page.goto(BACK + "/admin/content/webvitalbucket/report/", wait_until="domcontentloaded", timeout=30000)
        html = page.locator("body").inner_text(timeout=10000)
        if "Anonymous real-user performance" not in html or RELEASE not in html:
            raise AssertionError("superuser dashboard did not display real aggregated browser cohort")
        print("PASS actual Django superuser dashboard rendered aggregated Chrome-derived p75", flush=True)
        admin.close()

        # DNT and GPC each suppress collection even when selected for sampling.
        for signal, override in [
            ("DNT", 'Object.defineProperty(navigator,"doNotTrack",{get:()=> "1"});'),
            ("GPC", 'Object.defineProperty(navigator,"globalPrivacyControl",{get:()=> true});'),
        ]:
            private = browser.new_context(viewport={"width": 390, "height": 844})
            private.add_init_script("Math.random = () => 0;" + override)
            captured = []
            private.on("request", lambda req: captured.append(req.url) if "/api/field-vitals" in req.url else None)
            test_page = private.new_page()
            test_page.goto(FRONT + "/", wait_until="domcontentloaded", timeout=45000)
            test_page.wait_for_timeout(850)
            test_page.evaluate("window.dispatchEvent(new Event('pagehide'))")
            test_page.wait_for_timeout(300)
            if captured:
                raise AssertionError(f"{signal} privacy opt-out sent report")
            private.close()
            print(f"PASS {signal} prevents browser reporting", flush=True)
        context.close()
        browser.close()

    print("PASS real browser -> first-party endpoint -> token-authenticated Django -> histogram -> superuser report", flush=True)


if __name__ == "__main__":
    main()
